#!/usr/bin/env node

/**
 * The vocabulary of the grammars this Workbench is parsed by, taken from the grammars themselves.
 *
 * Nothing here decides anything. Tree-sitter generates a `node-types.json` beside every grammar it
 * builds — the complete list of node kinds that grammar can produce — and the grammars are in turn
 * generated from PostgreSQL's own `gram.y` and `kwlist.h`. So the list has an author, and it is
 * PostgreSQL. Every list this project wrote by hand was a guess at it, and every one of them was
 * wrong: the debugger named two statements the grammar does not produce, coverage missed seven,
 * and a hand-written map of literal kinds left `E'…'` and `X'…'` uncoloured.
 *
 * Two grammars parse this project, and they are not the same artifact:
 *
 *   sql      tree-sitter-postgres, the version Code Moniker locks
 *   plpgsql  the copy Code Moniker vendors and modifies — PostgreSQL block labels are identifiers
 *            and may be quoted, which upstream did not read
 *
 * Neither is reachable from this repository at build time: Code Moniker ships as a binary, and its
 * grammar lives in its own checkout and in a Cargo registry. So this reads them where they are and
 * writes what it found, to be committed. It runs when Code Moniker moves, not on every build — and
 * `e2e/postgres-grammar.test.ts` holds the running parser against what it wrote, so a Code Moniker
 * that has moved without this being re-run fails there rather than going quiet.
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";

const OUT = resolve("packages/sql/src/analysis/grammarKinds.ts");

/** Where Code Moniker is checked out; its vendored PL/pgSQL grammar is the one that parses. */
const CODE_MONIKER =
  process.env.CODE_MONIKER_ROOT ?? resolve(homedir(), "dev/projects/code-moniker");

const vendored = join(CODE_MONIKER, "crates/core/vendor/tree-sitter-plpgsql/src/node-types.json");

/** The SQL grammar is a crate, so it sits wherever Cargo unpacked the version Code Moniker locks. */
function crateNodeTypes(version) {
  const registry = resolve(homedir(), ".cargo/registry/src");
  if (!existsSync(registry)) return undefined;
  for (const index of readdirSync(registry)) {
    const file = join(
      registry,
      index,
      `tree-sitter-postgres-${version}`,
      "postgres/src/node-types.json",
    );
    if (existsSync(file)) return file;
  }
  return undefined;
}

/** The version Code Moniker locks, read from its lock file rather than assumed. */
function lockedVersion() {
  const lock = join(CODE_MONIKER, "Cargo.lock");
  if (!existsSync(lock)) return undefined;
  const entry = /name = "tree-sitter-postgres"\nversion = "([^"]+)"/u.exec(
    readFileSync(lock, "utf8"),
  );
  return entry?.[1];
}

/** What the vendored grammar says it is derived from, in its own words. */
function vendoredProvenance() {
  const readme = join(CODE_MONIKER, "crates/core/vendor/tree-sitter-plpgsql/README.md");
  if (!existsSync(readme)) return "unknown";
  const derived = /version `([^`]+)` at commit\n`([0-9a-f]+)`/u.exec(readFileSync(readme, "utf8"));
  return derived ? `tree-sitter-postgres ${derived[1]} at ${derived[2]}` : "unknown";
}

function namedKinds(file) {
  return [
    ...new Set(
      JSON.parse(readFileSync(file, "utf8"))
        .filter((node) => node.named === true && typeof node.type === "string")
        .map((node) => node.type),
    ),
  ].sort();
}

function fail(message) {
  process.stderr.write(
    `${message}\n\nThis reads the grammars where they live:\n` +
      `  PL/pgSQL  ${vendored}\n` +
      "  SQL       the tree-sitter-postgres crate Code Moniker locks, unpacked under ~/.cargo/registry\n\n" +
      "Point CODE_MONIKER_ROOT at a Code Moniker checkout, and build it once so Cargo unpacks the crate.\n",
  );
  process.exit(1);
}

const version = lockedVersion();
if (!version)
  fail(`No Cargo.lock under ${CODE_MONIKER}: cannot tell which grammar version parses.`);
if (!existsSync(vendored)) fail(`No vendored PL/pgSQL grammar at ${vendored}.`);
const sqlFile = crateNodeTypes(version);
if (!sqlFile) fail(`tree-sitter-postgres ${version} is not unpacked in any Cargo registry.`);

const sql = namedKinds(sqlFile);
const plpgsql = namedKinds(vendored);

const list = (kinds) => kinds.map((kind) => `  ${JSON.stringify(kind)},`).join("\n");

writeFileSync(
  OUT,
  `// Generated by scripts/sql/generate-grammar-kinds.mjs. Do not edit.
//
// Every node kind the grammars that parse this Workbench can produce, taken from the
// \`node-types.json\` Tree-sitter generates beside each one. The grammars are themselves generated
// from PostgreSQL's \`gram.y\` and \`kwlist.h\`, so this list is PostgreSQL's, not this project's.
//
// sql      tree-sitter-postgres ${version}
// plpgsql  ${vendoredProvenance()}, as Code Moniker vendors and modifies it

/** Node kinds of the SQL grammar. */
export const SQL_GRAMMAR_KINDS: readonly string[] = [
${list(sql)}
];

/** Node kinds of the PL/pgSQL grammar, which is not the same artifact as the SQL one. */
export const PLPGSQL_GRAMMAR_KINDS: readonly string[] = [
${list(plpgsql)}
];
`,
  "utf8",
);

process.stdout.write(
  `Grammar kinds written to ${OUT}\n` +
    `  sql      ${sql.length} kinds (tree-sitter-postgres ${version})\n` +
    `  plpgsql  ${plpgsql.length} kinds (${vendoredProvenance()})\n`,
);
