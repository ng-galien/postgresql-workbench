#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const POSTGRES_VERSION = "18.4";
const SOURCE_TAG = "REL_18_4";
const TREE_SITTER_POSTGRES_VERSION = "1.2.4";
const CODE_MONIKER_CLIENT_VERSION = "0.9.2";
const OUTPUT = resolve("packages/sql/src/analysis/generated/postgresKeywords.ts");

const sources = {
  sql: {
    path: `scripts/sql/upstream/postgresql/${SOURCE_TAG}/kwlist.h`,
    url: `https://github.com/postgres/postgres/blob/${SOURCE_TAG}/src/include/parser/kwlist.h`,
    sha256: "fdcdf3694513cba63b4016f63032472b686e381bb35f17c5d645bc2f6f1dac16",
  },
  plpgsqlReserved: {
    path: `scripts/sql/upstream/postgresql/${SOURCE_TAG}/pl_reserved_kwlist.h`,
    url: `https://github.com/postgres/postgres/blob/${SOURCE_TAG}/src/pl/plpgsql/src/pl_reserved_kwlist.h`,
    sha256: "32fdee4aebd1ff76283e36d15946dd81c38251baf3cf118545f986df043e9bac",
  },
  plpgsqlUnreserved: {
    path: `scripts/sql/upstream/postgresql/${SOURCE_TAG}/pl_unreserved_kwlist.h`,
    url: `https://github.com/postgres/postgres/blob/${SOURCE_TAG}/src/pl/plpgsql/src/pl_unreserved_kwlist.h`,
    sha256: "9c137b1d9e88934aabe57305d933ed7b72144bfed98679b2a7058e4527b7a03c",
  },
};

function verifiedSource(authority) {
  const path = resolve(authority.path);
  const source = readFileSync(path, "utf8");
  const actualSha = createHash("sha256").update(source).digest("hex");
  if (actualSha !== authority.sha256) {
    throw new Error(
      `PostgreSQL keyword source SHA mismatch for ${path}: expected ${authority.sha256}, got ${actualSha}`,
    );
  }
  return { path, source };
}

function validateEntries(entries, path, sourceEntryCount) {
  if (entries.length !== sourceEntryCount) {
    throw new Error(
      `Parsed ${entries.length} of ${sourceEntryCount} PG_KEYWORD entries from ${path}`,
    );
  }
  if (new Set(entries.map(({ word }) => word)).size !== entries.length) {
    throw new Error(`PostgreSQL keyword source ${path} contains duplicate words`);
  }
  if (entries.some(({ word }, index) => index > 0 && word <= entries[index - 1].word)) {
    throw new Error(`PostgreSQL keyword source ${path} is not strictly ASCII-sorted`);
  }
  return entries;
}

const categoryCodes = {
  UNRESERVED_KEYWORD: "U",
  COL_NAME_KEYWORD: "C",
  TYPE_FUNC_NAME_KEYWORD: "T",
  RESERVED_KEYWORD: "R",
};

function sqlKeywords(authority) {
  const { path, source } = verifiedSource(authority);
  const pattern =
    /^PG_KEYWORD\("([a-z][a-z0-9_]*)",\s*([A-Z][A-Z0-9_]*),\s*(UNRESERVED_KEYWORD|COL_NAME_KEYWORD|TYPE_FUNC_NAME_KEYWORD|RESERVED_KEYWORD),\s*(BARE_LABEL|AS_LABEL)\)/gmu;
  const entries = [...source.matchAll(pattern)].map((match) => ({
    word: match[1],
    label: match[1].toUpperCase(),
    token: match[2],
    category: categoryCodes[match[3]],
    bareLabel: match[4] === "BARE_LABEL",
  }));
  return validateEntries(entries, path, [...source.matchAll(/^PG_KEYWORD\(/gmu)].length);
}

function plpgsqlKeywords(authority, category) {
  const { path, source } = verifiedSource(authority);
  const pattern = /^PG_KEYWORD\("([a-z][a-z0-9_]*)",\s*([A-Z][A-Z0-9_]*)\)/gmu;
  const entries = [...source.matchAll(pattern)].map((match) => ({
    word: match[1],
    label: match[1].toUpperCase(),
    token: match[2],
    category,
  }));
  return validateEntries(entries, path, [...source.matchAll(/^PG_KEYWORD\(/gmu)].length);
}

const sql = sqlKeywords(sources.sql);
const plpgsql = [
  ...plpgsqlKeywords(sources.plpgsqlReserved, "R"),
  ...plpgsqlKeywords(sources.plpgsqlUnreserved, "U"),
].sort((left, right) => left.word.localeCompare(right.word));
if (new Set(plpgsql.map(({ word }) => word)).size !== plpgsql.length) {
  throw new Error("PostgreSQL PL/pgSQL reserved and unreserved keyword sources overlap");
}

const packageJson = JSON.parse(readFileSync(resolve("package.json"), "utf8"));
if (packageJson.dependencies?.["@code-moniker/client"] !== CODE_MONIKER_CLIENT_VERSION) {
  throw new Error(
    `Keyword authority expects @code-moniker/client@${CODE_MONIKER_CLIENT_VERSION}; package.json has ${packageJson.dependencies?.["@code-moniker/client"] ?? "none"}`,
  );
}

const sqlEntries = sql
  .map(
    ({ word, label, token, category, bareLabel }) =>
      `  { word: ${JSON.stringify(word)}, label: ${JSON.stringify(label)}, token: ${JSON.stringify(token)}, category: ${JSON.stringify(category)}, bareLabel: ${bareLabel} },`,
  )
  .join("\n");
const plpgsqlEntries = plpgsql
  .map(
    ({ word, label, token, category }) =>
      `  { word: ${JSON.stringify(word)}, label: ${JSON.stringify(label)}, token: ${JSON.stringify(token)}, category: ${JSON.stringify(category)} },`,
  )
  .join("\n");

const generated = `// Generated by scripts/sql/generate-postgres-keywords.mjs. Do not edit.
// biome-ignore-all format: generated source is checked byte-for-byte
// PostgreSQL source tag: ${SOURCE_TAG}

export const POSTGRES_SQL_KEYWORD_SOURCE = {
  postgresVersion: ${JSON.stringify(POSTGRES_VERSION)},
  sourceTag: ${JSON.stringify(SOURCE_TAG)},
  sourceUrl: ${JSON.stringify(sources.sql.url)},
  sourceSha256: ${JSON.stringify(sources.sql.sha256)},
  grammarPackage: ${JSON.stringify(`tree-sitter-postgres@${TREE_SITTER_POSTGRES_VERSION}`)},
  runtimePackage: ${JSON.stringify(`@code-moniker/client@${CODE_MONIKER_CLIENT_VERSION}`)},
} as const;

export const PLPGSQL_KEYWORD_SOURCES = {
  postgresVersion: ${JSON.stringify(POSTGRES_VERSION)},
  sourceTag: ${JSON.stringify(SOURCE_TAG)},
  reserved: {
    sourceUrl: ${JSON.stringify(sources.plpgsqlReserved.url)},
    sourceSha256: ${JSON.stringify(sources.plpgsqlReserved.sha256)},
  },
  unreserved: {
    sourceUrl: ${JSON.stringify(sources.plpgsqlUnreserved.url)},
    sourceSha256: ${JSON.stringify(sources.plpgsqlUnreserved.sha256)},
  },
  grammarPackage: ${JSON.stringify(`tree-sitter-postgres@${TREE_SITTER_POSTGRES_VERSION} (Code Moniker vendored PL/pgSQL grammar)`)},
  runtimePackage: ${JSON.stringify(`@code-moniker/client@${CODE_MONIKER_CLIENT_VERSION}`)},
} as const;

export const GENERATED_POSTGRES_SQL_KEYWORDS = [
${sqlEntries}
] as const;

export const GENERATED_PLPGSQL_KEYWORDS = [
${plpgsqlEntries}
] as const;
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(OUTPUT, "utf8");
  if (current !== generated) {
    throw new Error(
      `${OUTPUT} is stale. Run node scripts/sql/generate-postgres-keywords.mjs and commit the result.`,
    );
  }
} else {
  writeFileSync(OUTPUT, generated, "utf8");
  process.stdout.write(
    `PostgreSQL keyword catalogs written to ${OUTPUT}\n` +
      `  SQL ${sql.length}; PL/pgSQL ${plpgsql.length}; PostgreSQL ${POSTGRES_VERSION} (${SOURCE_TAG})\n`,
  );
}
